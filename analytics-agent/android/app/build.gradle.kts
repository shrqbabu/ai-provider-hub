/**
 * Build configuration is read from `local.defaults.properties` (git-ignored) or,
 * in CI, from environment variables.
 *
 * ONLY public values are allowed here:
 *   - SUPABASE_URL
 *   - SUPABASE_PUBLISHABLE_KEY  (the anon/publishable key, safe for clients)
 *   - ANALYTICS_API_URL
 *
 * The service-role key, the JWT secret, AI provider keys and SQL credentials
 * must NEVER appear in this file, in BuildConfig, in strings.xml or in the APK.
 */
val localProps = Properties().apply {
    val file = rootProject.file("local.defaults.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun config(key: String, fallback: String = ""): String =
    (System.getenv(key) ?: localProps.getProperty(key) ?: fallback).trim()

